"""Tests for the RLS generator.

These lean adversarial on purpose. The generator's whole value is that no input
produces an unprotected table, and that claim is only worth something if the
inputs tried are the ones an attacker would try.
"""

from __future__ import annotations

import pytest
from loopit_provision import (
    APP_ROLE,
    ColumnSpec,
    IdentifierError,
    RlsError,
    TableSpec,
    assert_secured,
    emit_migration,
    emit_table,
    generate_policies,
)


def _tasks() -> TableSpec:
    return TableSpec(
        name="tasks",
        columns=(
            ColumnSpec("title", "text", nullable=False),
            ColumnSpec("done", "boolean", nullable=False, default="false"),
        ),
        access="owner",
    )


class TestIdentifiers:
    @pytest.mark.parametrize(
        "name",
        [
            'x"; DROP SCHEMA public CASCADE; --',
            "tasks; DELETE FROM users",
            "Tasks",
            "tasks-1",
            "1tasks",
            "",
            "select",
            "user",
            "xmin",
            "a" * 64,
        ],
    )
    def test_hostile_table_names_are_refused(self, name: str) -> None:
        with pytest.raises((IdentifierError, RlsError)):
            TableSpec(name=name, columns=(ColumnSpec("title", "text"),), access="owner")

    def test_hostile_column_names_are_refused(self) -> None:
        with pytest.raises(IdentifierError):
            ColumnSpec('t" text); DROP TABLE users; --', "text")

    def test_a_name_that_only_differs_past_63_bytes_is_refused(self) -> None:
        # Postgres would truncate both to the same object, quietly merging two
        # tables that the schema believes are distinct.
        with pytest.raises(IdentifierError, match="truncate"):
            TableSpec(name="a" * 70, columns=(ColumnSpec("t", "text"),), access="owner")


class TestColumnConstraints:
    def test_unsupported_type_is_refused(self) -> None:
        with pytest.raises(RlsError, match="unsupported type"):
            ColumnSpec("blob", "bytea")

    def test_type_is_not_a_sql_injection_point(self) -> None:
        with pytest.raises(RlsError, match="unsupported type"):
            ColumnSpec("t", "text); DROP TABLE users; --")

    def test_arbitrary_default_expressions_are_refused(self) -> None:
        # A default is raw SQL evaluated with migration privileges.
        with pytest.raises(RlsError, match="unsupported default"):
            ColumnSpec("t", "text", default="(SELECT secret FROM platform_keys LIMIT 1)")

    def test_allowed_default_is_kept(self) -> None:
        assert "DEFAULT now()" in ColumnSpec("at", "timestamptz", default="now()").to_sql()


class TestOwnershipIsGenerated:
    def test_agent_cannot_declare_the_ownership_column(self) -> None:
        # If it could, it could declare it nullable or as text and defeat the
        # policies generated against it.
        with pytest.raises(RlsError, match="generated by the provisioning tool"):
            TableSpec(
                name="tasks",
                columns=(ColumnSpec("user_id", "text"),),
                access="owner",
            )

    def test_agent_cannot_declare_the_primary_key(self) -> None:
        with pytest.raises(RlsError, match="primary key is generated"):
            TableSpec(name="tasks", columns=(ColumnSpec("id", "text"),), access="owner")

    def test_ownership_column_is_not_null(self) -> None:
        sql = "\n".join(emit_table(_tasks()))
        assert '"user_id" uuid NOT NULL DEFAULT auth.uid()' in sql

    def test_tenant_tables_are_owned_by_org_id(self) -> None:
        spec = TableSpec(
            name="invoices",
            columns=(ColumnSpec("amount", "numeric"),),
            access="tenant",
        )
        sql = "\n".join(emit_table(spec))
        assert '"org_id" uuid NOT NULL' in sql
        assert "request.jwt.claims" in sql

    def test_duplicate_columns_are_refused(self) -> None:
        with pytest.raises(RlsError, match="twice"):
            TableSpec(
                name="tasks",
                columns=(ColumnSpec("title", "text"), ColumnSpec("title", "text")),
                access="owner",
            )

    def test_a_table_with_no_columns_is_refused(self) -> None:
        with pytest.raises(RlsError, match="no columns"):
            TableSpec(name="tasks", columns=(), access="owner")


class TestPolicies:
    def test_every_command_gets_a_policy(self) -> None:
        policies = generate_policies("tasks", access="owner", ownership_column="user_id")
        assert {p.command for p in policies} == {"select", "insert", "update", "delete"}

    def test_writes_carry_with_check(self) -> None:
        # USING alone would let a user update one of their own rows into another
        # user's ownership, writing across the tenant boundary.
        policies = {
            p.command: p
            for p in generate_policies("tasks", access="owner", ownership_column="user_id")
        }
        assert policies["insert"].with_check is not None
        assert policies["update"].with_check is not None
        assert policies["update"].using is not None

    def test_insert_has_no_using_clause(self) -> None:
        policies = {
            p.command: p
            for p in generate_policies("tasks", access="owner", ownership_column="user_id")
        }
        assert policies["insert"].using is None

    def test_reads_are_scoped_to_the_caller(self) -> None:
        policies = {
            p.command: p
            for p in generate_policies("tasks", access="owner", ownership_column="user_id")
        }
        assert policies["select"].using == '"user_id" = auth.uid()'

    def test_policies_target_the_app_role_only(self) -> None:
        sql = "\n".join(emit_table(_tasks()))
        assert sql.count(f'TO "{APP_ROLE}"') >= 4


class TestTableIsLockedDown:
    def test_rls_is_enabled_and_forced(self) -> None:
        sql = "\n".join(emit_table(_tasks()))
        assert 'ALTER TABLE "public"."tasks" ENABLE ROW LEVEL SECURITY;' in sql
        # Without FORCE the owning role bypasses every policy, and generated
        # apps routinely connect as the role that owns their tables.
        assert 'ALTER TABLE "public"."tasks" FORCE ROW LEVEL SECURITY;' in sql

    def test_public_is_revoked(self) -> None:
        sql = "\n".join(emit_table(_tasks()))
        assert 'REVOKE ALL ON "public"."tasks" FROM PUBLIC;' in sql

    def test_ownership_column_is_indexed(self) -> None:
        # Every policy predicate filters on it; without an index each query is a
        # sequential scan.
        sql = "\n".join(emit_table(_tasks()))
        assert 'CREATE INDEX IF NOT EXISTS "tasks_user_id_idx"' in sql

    def test_no_permissive_policy_is_ever_emitted(self) -> None:
        sql = "\n".join(emit_table(_tasks())).lower()
        assert "using (true)" not in sql


class TestMigration:
    def test_updated_at_is_maintained_by_a_trigger(self) -> None:
        # Otherwise updated_at defaults to the insert time and never changes -
        # a column that looks maintained but silently is not.
        sql = emit_migration([_tasks()])
        assert "CREATE OR REPLACE FUNCTION public.loopit_set_updated_at()" in sql
        assert 'CREATE OR REPLACE TRIGGER "tasks_set_updated_at"' in sql
        # A mutable search_path lets a caller hijack the function via a
        # shadowing object in an earlier schema.
        assert "SET search_path = pg_catalog, public" in sql

    def test_the_touch_function_is_defined_once_for_many_tables(self) -> None:
        specs = [
            _tasks(),
            TableSpec(name="notes", columns=(ColumnSpec("body", "text"),), access="owner"),
        ]
        assert emit_migration(specs).count("CREATE OR REPLACE FUNCTION") == 1

    def test_migration_is_transactional(self) -> None:
        # A partial apply must not leave a created-but-unsecured table behind.
        sql = emit_migration([_tasks()])
        assert sql.lstrip().splitlines()[3] == "BEGIN;"
        assert sql.rstrip().endswith("COMMIT;")

    def test_every_table_in_a_migration_is_secured(self) -> None:
        specs = [
            _tasks(),
            TableSpec(name="notes", columns=(ColumnSpec("body", "text"),), access="owner"),
        ]
        sql = emit_migration(specs)
        for table in ("tasks", "notes"):
            assert f'ALTER TABLE "public"."{table}" FORCE ROW LEVEL SECURITY;' in sql

    def test_empty_migration_is_refused(self) -> None:
        with pytest.raises(RlsError, match="at least one table"):
            emit_migration([])

    def test_duplicate_tables_are_refused(self) -> None:
        with pytest.raises(RlsError, match="same table twice"):
            emit_migration([_tasks(), _tasks()])


class TestAssertSecured:
    """The last-line check must actually fail on the failures it names."""

    def test_missing_enable_is_caught(self) -> None:
        statements = [s for s in emit_table(_tasks()) if "ENABLE ROW LEVEL" not in s]
        with pytest.raises(RlsError, match="RLS is not enabled"):
            assert_secured(statements, "tasks")

    def test_missing_force_is_caught(self) -> None:
        statements = [s for s in emit_table(_tasks()) if "FORCE ROW LEVEL" not in s]
        with pytest.raises(RlsError, match="owner bypasses"):
            assert_secured(statements, "tasks")

    def test_missing_revoke_is_caught(self) -> None:
        statements = [s for s in emit_table(_tasks()) if "REVOKE ALL" not in s]
        with pytest.raises(RlsError, match="PUBLIC access is not revoked"):
            assert_secured(statements, "tasks")

    def test_missing_policies_are_caught(self) -> None:
        statements = [s for s in emit_table(_tasks()) if "CREATE POLICY" not in s]
        with pytest.raises(RlsError, match="no policy exists"):
            assert_secured(statements, "tasks")

    def test_a_permissive_policy_is_caught(self) -> None:
        statements = [*emit_table(_tasks()), 'CREATE POLICY "x" ON "public"."tasks" USING (true);']
        with pytest.raises(RlsError, match="permissive"):
            assert_secured(statements, "tasks")

    def test_a_table_created_without_being_secured_is_caught(self) -> None:
        with pytest.raises(RlsError, match="no CREATE TABLE"):
            assert_secured(['CREATE TABLE "public"."other" (x text);'], "tasks")

    def test_generated_output_passes_its_own_check(self) -> None:
        assert_secured(list(emit_table(_tasks())), "tasks")
